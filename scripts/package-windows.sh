#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/dist/Maze-Windows-Portable"
BIN="/ucrt64/bin"
SHARE="/ucrt64/share"
rm -rf "$OUT" "$ROOT/dist/Maze-Windows-Portable.zip"
mkdir -p "$OUT"
cp "$ROOT/target/x86_64-pc-windows-gnu/release/maze.exe" "$OUT/maze.exe"

# GTK4/Libadwaita depend on a large DLL graph. Shipping the UCRT64 runtime DLL
# set avoids missing transitive DLLs on machines without MSYS2 installed.
find "$BIN" -maxdepth 1 -type f -iname '*.dll' -exec cp -f '{}' "$OUT/" \;

# GTK/GdkPixbuf/GLib runtime data used by GTK at startup and while rendering.
for item in \
  glib-2.0/schemas \
  icons \
  themes \
  gtk-4.0 \
  libadwaita-1 \
  gdk-pixbuf-2.0; do
  if [[ -e "$SHARE/$item" ]]; then
    mkdir -p "$OUT/share/$(dirname "$item")"
    cp -a "$SHARE/$item" "$OUT/share/$item"
  fi
done

# Include relevant runtime configuration when provided by the MSYS2 packages.
if [[ -d /ucrt64/etc/gtk-4.0 ]]; then
  mkdir -p "$OUT/etc"
  cp -a /ucrt64/etc/gtk-4.0 "$OUT/etc/"
fi

cat > "$OUT/Run-Maze.bat" <<'BAT'
@echo off
setlocal
set "APP_DIR=%~dp0"
set "PATH=%APP_DIR%;%APP_DIR%\bin;%PATH%"
set "XDG_DATA_DIRS=%APP_DIR%\share"
set "GSETTINGS_SCHEMA_DIR=%APP_DIR%\share\glib-2.0\schemas"
set "GTK_DATA_PREFIX=%APP_DIR%"
set "GTK_EXE_PREFIX=%APP_DIR%"
set "GDK_PIXBUF_MODULEDIR=%APP_DIR%\lib\gdk-pixbuf-2.0\2.10.0\loaders"
set "GDK_PIXBUF_MODULE_FILE=%APP_DIR%\lib\gdk-pixbuf-2.0\2.10.0\loaders.cache"
set "GTK_THEME=Adwaita"
start "" "%APP_DIR%maze.exe"
BAT

cat > "$OUT/README-Windows.txt" <<'TXT'
Maze - Portable Windows build

Run Run-Maze.bat. Keep the entire extracted folder together; do not move
maze.exe out of this folder. This package bundles the GTK4/Libadwaita DLLs
and runtime data so MSYS2 should not need to be installed on the target PC.

If Windows reports another missing DLL, please report the exact filename and
Windows version. This package is generated by the GitHub Actions Windows
portable-build workflow.
TXT

# Keep a plain executable too, for users who want to launch it directly.
mkdir -p "$ROOT/dist"
cd "$ROOT/dist"
zip -qr Maze-Windows-Portable.zip Maze-Windows-Portable
